"""Markdown export, suitable for pull requests, issues and wikis."""
from __future__ import annotations

from backend.schemas import ExplanationSource, Report, Severity
from backend.storage.exporters.common import format_duration, format_time, source_label


def _escape_cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def to_markdown(report: Report) -> str:
    summary = report.summary
    lines: list[str] = [
        f"# Secura security report: {report.target}",
        "",
        f"**Risk grade {report.risk.grade}** ({report.risk.score}/100, {report.risk.label}) · "
        f"{summary.total} finding(s)",
        "",
        "| | |",
        "|---|---|",
        f"| Target | {_escape_cell(report.target)} |",
        f"| Type | {report.target_type.label} |",
        f"| Started | {format_time(report.started_at)} |",
        f"| Duration | {format_duration(report.duration_seconds)} |",
        f"| Files scanned | {report.stats.files_scanned} |",
        f"| Report ID | `{report.report_id}` |",
        "",
        "## Summary",
        "",
        "| Severity | Findings |",
        "|---|---:|",
    ]
    for severity in Severity.ordered():
        lines.append(f"| {severity.label} | {summary.count(severity)} |")
    lines.append(f"| **Total** | **{summary.total}** |")

    if report.engines:
        lines += ["", "## Engines", "", "| Engine | Status | Findings | Detail |", "|---|---|---:|---|"]
        for engine in report.engines:
            lines.append(f"| {engine.label} | {engine.status} | {engine.findings} | {_escape_cell(engine.detail)} |")

    if report.notes:
        lines += ["", "## Notes", ""]
        lines += [f"- {note}" for note in report.notes]

    lines += ["", "## Findings", ""]
    if not report.findings:
        lines.append("_No findings were recorded for this scan._")

    for index, finding in enumerate(report.findings, start=1):
        meta = [f"**Severity:** {finding.severity.label}",
                f"**Confidence:** {int(round(finding.confidence * 100))}%"]
        if finding.rule_id:
            meta.append(f"**Rule:** `{finding.rule_id}`")
        if finding.cwe:
            meta.append(f"**{finding.cwe}**")
        lines += [
            f"### {index}. {finding.title}",
            "",
            f"`{finding.location or 'location not recorded'}`",
            "",
            " · ".join(meta),
            "",
        ]
        if finding.description:
            lines += [finding.description, ""]
        if finding.snippet:
            lines += ["    " + line for line in finding.snippet.splitlines()]
            lines.append("")
        source = source_label(finding)
        lines += [
            "**Why it is dangerous**",
            "",
            finding.why_dangerous or "_No explanation recorded._",
            "",
            "**How to fix it**",
            "",
            finding.how_to_fix or "_No remediation recorded._",
            "",
        ]
        if finding.explanation_source != ExplanationSource.NONE:
            lines += [f"_Explanation: {source}_", ""]
        links = [ref for ref in finding.references[:4] if ref.startswith(("https://", "http://"))]
        if links:
            lines += ["References: " + ", ".join(f"<{ref}>" for ref in links), ""]

    lines += [
        "---",
        f"Generated by Secura {report.tool_version}. Scan only code you own or are authorised to test.",
    ]
    return "\n".join(lines) + "\n"
